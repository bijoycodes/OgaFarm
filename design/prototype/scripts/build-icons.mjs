// Generates src/shared/ui/icons.generated.ts with only the regular-weight Phosphor icons we use.
// Phosphor components carry all six weights; extracting one weight keeps the app small for low-bandwidth users.
// Run: node scripts/build-icons.mjs (re-run after adding a name to ICONS below).
import { writeFileSync } from 'node:fs';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

const ICONS = {
  home: 'House', store: 'Storefront', box: 'Package', receipt: 'Receipt', bell: 'Bell', user: 'User', users: 'Users',
  search: 'MagnifyingGlass', plus: 'Plus', share: 'ShareNetwork', check: 'Check', card: 'CreditCard', shield: 'ShieldCheck',
  pin: 'MapPin', clock: 'Clock', menu: 'List', close: 'X', copy: 'Copy', chat: 'ChatCircle', whatsapp: 'WhatsappLogo',
  upload: 'UploadSimple', chev: 'CaretRight', back: 'ArrowLeft', alert: 'Warning', info: 'Info', leaf: 'Leaf', egg: 'Egg',
  sack: 'Basket', fish: 'Fish', seed: 'Plant', truck: 'Truck', briefcase: 'Briefcase', filter: 'Funnel', edit: 'PencilSimple',
  image: 'Image', star: 'Star', lock: 'Lock', wifi: 'WifiSlash', phone: 'DeviceMobile', tag: 'Tag', grid: 'SquaresFour',
  doc: 'FileText', list: 'ListBullets', logout: 'SignOut', eye: 'Eye', eyeOff: 'EyeSlash', mail: 'EnvelopeSimple',
  seal: 'SealCheck', coins: 'HandCoins', handshake: 'Handshake', scales: 'Scales', sun: 'Sun', moon: 'Moon', monitor: 'Monitor', camera: 'Camera', flag: 'Flag', map: 'MapTrifold', route: 'Path', gauge: 'Gauge', calendar: 'CalendarBlank', navigation: 'NavigationArrow', thumbsup: 'ThumbsUp'
};

// A few icons also need the filled weight (e.g. star ratings). Key is the name used in <Icon name>.
const FILLED = { starFill: 'Star' };

const out = {};
for (const [key, name] of Object.entries(ICONS)) {
  const mod = await import(`@phosphor-icons/react/dist/ssr/${name}`);
  const svg = renderToStaticMarkup(createElement(mod[name], { weight: 'regular' }));
  out[key] = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '').replace(/<rect width="256" height="256" fill="none"><\/rect>/, '');
}
for (const [key, name] of Object.entries(FILLED)) {
  const mod = await import(`@phosphor-icons/react/dist/ssr/${name}`);
  const svg = renderToStaticMarkup(createElement(mod[name], { weight: 'fill' }));
  out[key] = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '').replace(/<rect width="256" height="256" fill="none"><\/rect>/, '');
}
const body = `/* Generated by scripts/build-icons.mjs from @phosphor-icons/react (regular weight, 256 viewBox). Do not edit by hand. */\nexport const ICON_PATHS: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync('src/shared/ui/icons.generated.ts', body);
console.log(`Wrote ${Object.keys(out).length} icons`);
